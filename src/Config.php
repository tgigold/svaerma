<?php

declare(strict_types=1);

namespace App;

/**
 * Application configuration: built-in defaults merged with config/config.php.
 * New keys get a default here, so existing installations keep working after updates.
 */
final class Config
{
    /** @param array<string, mixed> $values */
    private function __construct(private array $values)
    {
    }

    /** @return array<string, mixed> */
    public static function defaults(): array
    {
        return [
            // APP_ENV=dev allows plain HTTP locally, e.g. before setup has written a config.
            'env' => getenv('APP_ENV') === 'dev' ? 'dev' : 'prod',
            'base_url' => '',
            'contact_email' => '',
            'timezone' => 'Europe/Berlin',
            'db_path' => APP_ROOT . '/data/app.sqlite',
            'data_dir' => APP_ROOT . '/data',
            'osm' => [
                'overpass_url' => 'https://overpass-api.de/api/interpreter',
                // Tried in order when the main endpoint fails (see wiki.openstreetmap.org/wiki/Overpass_API).
                'overpass_fallback_urls' => ['https://overpass.private.coffee/api/interpreter'],
                'photon_url' => 'https://photon.komoot.io/api/',
                'photon_reverse_url' => 'https://photon.komoot.io/reverse',
                'nominatim_url' => 'https://nominatim.openstreetmap.org/search',
                'search_provider' => 'photon',
                'tile_url' => 'https://tile.openstreetmap.org/{z}/{x}/{y}.png',
                'cache_ttl' => 86400,
                'timeout' => 15,
                // Per Overpass endpoint; kept short so the Photon fallback answers quickly.
                'overpass_timeout' => 12,
            ],
        ];
    }

    public static function path(): string
    {
        return APP_ROOT . '/config/config.php';
    }

    public static function exists(): bool
    {
        return is_file(self::path());
    }

    public static function load(): self
    {
        $local = [];
        if (self::exists()) {
            $local = require self::path();
            if (!is_array($local)) {
                throw new \RuntimeException('config/config.php must return an array.');
            }
        }
        return self::fromArray($local);
    }

    /** @param array<string, mixed> $values */
    public static function fromArray(array $values): self
    {
        return new self(self::merge(self::defaults(), $values));
    }

    /**
     * Recursive merge where lists (e.g. fallback URLs) are replaced as a whole,
     * so an empty list in config.php really means "none".
     *
     * @param array<mixed> $base
     * @param array<mixed> $override
     * @return array<mixed>
     */
    private static function merge(array $base, array $override): array
    {
        foreach ($override as $key => $value) {
            $base[$key] = is_array($value) && !array_is_list($value) && is_array($base[$key] ?? null)
                ? self::merge($base[$key], $value)
                : $value;
        }
        return $base;
    }

    /**
     * Read a value by dot path, e.g. "osm.overpass_url".
     */
    public function get(string $key, mixed $default = null): mixed
    {
        $value = $this->values;
        foreach (explode('.', $key) as $part) {
            if (!is_array($value) || !array_key_exists($part, $value)) {
                return $default;
            }
            $value = $value[$part];
        }
        return $value;
    }

    public function isDev(): bool
    {
        return $this->get('env') === 'dev';
    }

    /**
     * Write a config file containing only the given (non-default) values.
     *
     * @param array<string, mixed> $values
     */
    public static function write(array $values, ?string $path = null): void
    {
        $path ??= self::path();
        $code = "<?php\n\n// Generated by setup on " . gmdate('Y-m-d H:i') . " UTC.\n"
            . "// See config/config.example.php for all available options.\n\n"
            . 'return ' . var_export($values, true) . ";\n";
        if (file_put_contents($path, $code, LOCK_EX) === false) {
            throw new \RuntimeException("Could not write $path – check write permissions.");
        }
        @chmod($path, 0640);
    }
}
